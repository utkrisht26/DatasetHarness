"""Documentation-as-byproduct (PHASE0-CONTRACT §0.6, OUTLINE §4.1).

Auto-emits, from the Job Spec + run stats, the artifacts the contract promises at
build end: a Datasheet (Datasheets for Datasets), a Croissant JSON-LD descriptor
(MLCommons), and an HF-style dataset card. These are derived, never hand-written — the
Job Spec doubles as their source, so documentation cannot drift from the build.
"""

from __future__ import annotations

import json
from pathlib import Path


def datasheet_md(spec, stats: dict) -> str:
    """Render a Datasheet from the spec's motivation/uses/distribution + run stats."""
    counts = stats.get("counts_by_split", {})
    lines = [
        f"# Datasheet — {spec.name}",
        "",
        f"> {spec.description}",
        "",
        "## Motivation",
        spec.motivation,
        "",
        "## Composition",
        f"- Total records: **{stats.get('total_records', 0)}**",
        f"- Splits: {counts or 'n/a'}",
        f"- Modality: {spec.modality} · Languages: {', '.join(spec.languages)}",
        f"- Task categories: {', '.join(spec.task_categories)}",
        f"- Verifiability tier: {int(spec.verifiability_tier)}",
        "",
        "## Collection process",
        f"- Discovery mode: {spec.discovery.mode.value} across channels "
        f"{', '.join(c.value for c in spec.discovery.channels)}",
        f"- Accepted / generated: {stats.get('accepted', 0)} / {stats.get('generated', 0)} "
        f"(accept rate {stats.get('accept_rate', 0.0):.1%})",
        f"- Dropped — quality: {stats.get('dropped_quality', 0)}, "
        f"verifier: {stats.get('dropped_verifier', 0)}, jury: {stats.get('dropped_jury', 0)}, "
        f"duplicate: {stats.get('duplicates', 0)}, dead-lettered: {stats.get('dead_lettered', 0)}",
        f"- Contamination-flagged: {stats.get('contaminated', 0)}",
        "",
        "## Uses",
        f"- Intended: {', '.join(spec.intended_uses)}",
        f"- Out of scope: {', '.join(spec.out_of_scope_uses) or 'unspecified'}",
        "",
        "## Distribution",
        f"- License: {spec.output_license}",
        f"- Target: {spec.distribution_target or 'local'}",
        f"- Maintainer: {spec.maintainer or 'unspecified'}",
        "",
        "## Provenance",
        "Every record carries source lineage, generation lineage (model + prompt hash), "
        "verifier/judge results, a dedup cluster id, and a contamination flag "
        "(see `lineage.json` and the record schema).",
    ]
    return "\n".join(lines) + "\n"


def croissant_json(spec, files: list[str], stats: dict) -> dict:
    """A minimal MLCommons Croissant (JSON-LD) descriptor for the dataset."""
    job_id = spec.job_id or spec.name
    return {
        "@context": {"@vocab": "https://schema.org/", "cr": "http://mlcommons.org/croissant/"},
        "@type": "Dataset",
        "name": spec.name,
        "description": spec.description,
        "license": spec.output_license,
        "creator": spec.maintainer,
        "keywords": list(spec.task_categories),
        "inLanguage": list(spec.languages),
        "identifier": job_id,
        "distribution": [
            {"@type": "cr:FileObject", "@id": f, "name": f, "encodingFormat": _fmt(f)}
            for f in files
        ],
        "recordSet": [
            {
                "@type": "cr:RecordSet",
                "@id": "records",
                "name": "records",
                "description": f"{stats.get('total_records', 0)} records; splits "
                f"{stats.get('counts_by_split', {})}",
            }
        ],
    }


def dataset_card_md(spec, stats: dict) -> str:
    """HF dataset card: YAML frontmatter + a short human body."""
    front = [
        "---",
        f"license: {spec.output_license.lower()}",
        "task_categories:",
        *[f"  - {c}" for c in spec.task_categories],
        "language:",
        *[f"  - {lang}" for lang in spec.languages],
        f"size_categories:\n  - {_size_bucket(stats.get('total_records', 0))}",
        "---",
        "",
    ]
    body = [
        f"# {spec.name}",
        "",
        spec.description,
        "",
        f"- **Records:** {stats.get('total_records', 0)} · **Splits:** {stats.get('counts_by_split', {})}",
        f"- **Verifiability tier:** {int(spec.verifiability_tier)}",
        f"- **Intended uses:** {', '.join(spec.intended_uses)}",
        "",
        "Generated by the Agentic Dataset Harness (Engine B). See `datasheet.md` for full provenance.",
    ]
    return "\n".join(front + body) + "\n"


def emit_docs(spec, *, stats: dict, files: list[str], out_dir: str | Path) -> list[Path]:
    """Write datasheet.md + croissant.json + README.md; returns the paths written."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []

    datasheet = out / "datasheet.md"
    datasheet.write_text(datasheet_md(spec, stats), encoding="utf-8")
    written.append(datasheet)

    croissant = out / "croissant.json"
    croissant.write_text(json.dumps(croissant_json(spec, files, stats), indent=2), encoding="utf-8")
    written.append(croissant)

    card = out / "README.md"
    card.write_text(dataset_card_md(spec, stats), encoding="utf-8")
    written.append(card)
    return written


_MIME_BY_SUFFIX = {
    ".parquet": "application/vnd.apache.parquet",
    ".jsonl": "application/jsonl",
    ".mp4": "video/mp4",
    ".webm": "video/webm",
    ".mov": "video/quicktime",
    ".mkv": "video/x-matroska",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".png": "image/png",
    ".txt": "text/plain",
}


def _fmt(filename: str) -> str:
    """MIME type for a dataset file; unknown suffixes stay honest (octet-stream)."""
    return _MIME_BY_SUFFIX.get(Path(filename).suffix.lower(), "application/octet-stream")


def _size_bucket(n: int) -> str:
    for bound, label in ((1_000, "n<1K"), (10_000, "1K<n<10K"), (100_000, "10K<n<100K")):
        if n < bound:
            return label
    return "100K<n<1M"
