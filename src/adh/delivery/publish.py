"""Packaging / publishing to the HF Hub (OUTLINE §4.3).

Pushes a written dataset directory (shards + ``manifest.jsonl`` + ``datasheet.md`` +
``croissant.json``, as produced by :func:`adh.delivery.write_dataset` /
:func:`adh.delivery.emit_docs`) to a Hugging Face Hub dataset repo, with the license
stamped into the dataset card (README.md YAML frontmatter) and a source-provenance
summary appended to its body.

Ports & adapters: :class:`HubClient` is a minimal Protocol over the two HfApi calls
we need; tests inject fakes, production lazy-imports ``huggingface_hub`` behind
:class:`HfApiHubClient` (extra ``adh[publish]``). Publishing is always an explicit
call — nothing in the harness uploads on its own — and repos default to **private**.
"""

from __future__ import annotations

import json
import logging
from collections.abc import Iterator, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Protocol, runtime_checkable
from urllib.parse import urlparse

import yaml

from .writer import DeliveryResult

logger = logging.getLogger(__name__)

_REPO_TYPE = "dataset"
_MANIFEST_NAME = "manifest.jsonl"
_DOC_FILES = ("datasheet.md", "croissant.json")
_CARD_NAME = "README.md"
_PAYLOAD_KINDS = frozenset({"asset", "shard"})
_SHARD_SUFFIXES = frozenset({".jsonl", ".parquet"})
_PROVENANCE_HEADING = "Source provenance"
_DEFAULT_COMMIT_MESSAGE = "Publish dataset generated by the Agentic Dataset Harness"


class PublishRefusedError(RuntimeError):
    """Public upload refused while unknown-license assets are present.

    Distribution consent is separate from acquisition consent: the spec flag
    that let unknown-license assets IN never authorizes pushing them PUBLIC.
    """

    def __init__(self, unknown_assets: int) -> None:
        super().__init__(
            f"refusing PUBLIC upload: {unknown_assets} asset(s) carry an unknown license. "
            "Publish privately (the default), or re-run with --allow-unknown-licenses "
            "(allow_unknown_licensed_assets=True) to override."
        )
        self.unknown_assets = unknown_assets


# --- ports --------------------------------------------------------------------


@runtime_checkable
class HubClient(Protocol):
    """Minimal port over ``huggingface_hub.HfApi`` used for dataset publishing."""

    def create_repo(
        self,
        repo_id: str,
        *,
        repo_type: str = "dataset",
        private: bool = True,
        exist_ok: bool = True,
    ) -> str:
        """Create (or adopt) the repo; returns the repo URL."""
        ...

    def upload_file(
        self,
        *,
        path_or_fileobj: str,
        path_in_repo: str,
        repo_id: str,
        repo_type: str = "dataset",
        commit_message: str = "",
    ) -> str:
        """Upload one file; returns a URL for the committed file."""
        ...


@dataclass(frozen=True)
class HfApiHubClient:
    """Production adapter wrapping a lazily-constructed ``huggingface_hub.HfApi``."""

    api: Any  # huggingface_hub.HfApi — typed loosely so the extra stays optional

    def create_repo(
        self,
        repo_id: str,
        *,
        repo_type: str = "dataset",
        private: bool = True,
        exist_ok: bool = True,
    ) -> str:
        created = self.api.create_repo(
            repo_id=repo_id, repo_type=repo_type, private=private, exist_ok=exist_ok
        )
        return str(created)

    def upload_file(
        self,
        *,
        path_or_fileobj: str,
        path_in_repo: str,
        repo_id: str,
        repo_type: str = "dataset",
        commit_message: str = "",
    ) -> str:
        info = self.api.upload_file(
            path_or_fileobj=path_or_fileobj,
            path_in_repo=path_in_repo,
            repo_id=repo_id,
            repo_type=repo_type,
            commit_message=commit_message,
        )
        # CommitInfo carries .commit_url on recent hub versions; fall back defensively.
        url = getattr(info, "commit_url", None) or getattr(info, "url", None)
        return str(url) if url else _fallback_file_url(repo_id, repo_type, path_in_repo)


def _fallback_file_url(repo_id: str, repo_type: str, path_in_repo: str) -> str:
    prefix = {"dataset": "datasets", "space": "spaces"}.get(repo_type)
    repo_path = f"{prefix}/{repo_id}" if prefix else repo_id
    return f"https://huggingface.co/{repo_path}/blob/main/{path_in_repo}"


def default_hub_client() -> HubClient:
    """Build the real client; raises with an install hint when the extra is absent."""
    try:
        from huggingface_hub import HfApi  # type: ignore
    except ImportError as exc:
        raise RuntimeError(
            "publishing to the HF Hub requires 'huggingface_hub'; "
            "install with: pip install 'adh[publish]'"
        ) from exc
    return HfApiHubClient(api=HfApi())


# --- results ------------------------------------------------------------------


@dataclass(frozen=True)
class PublishFile:
    """One file in an upload plan: local source and its repo-relative destination."""

    local_path: Path
    repo_path: str
    url: str | None = None  # filled after upload; None in dry runs


@dataclass(frozen=True)
class PublishResult:
    """Outcome of either a planned dry run or a completed Hub publication."""

    repo_id: str
    private: bool
    dry_run: bool
    uploads: tuple[PublishFile, ...]
    url: str | None = None  # repo URL; None for dry runs


# --- input resolution ---------------------------------------------------------


@dataclass(frozen=True)
class _ManifestData:
    upload_files: tuple[Path, ...] = ()
    record_shards: tuple[Path, ...] = ()
    job_id: str | None = None


@dataclass(frozen=True)
class _DatasetBundle:
    directory: Path
    upload_files: tuple[Path, ...]
    record_shards: tuple[Path, ...]
    manifest_path: Path | None
    job_id: str | None


def _iter_jsonl_objects(path: Path, *, ignore_invalid: bool = False) -> Iterator[dict[str, Any]]:
    """Yield JSON objects with useful errors and bounded memory usage."""
    with path.open(encoding="utf-8") as lines:
        for line_number, line in enumerate(lines, start=1):
            stripped = line.strip()
            if not stripped:
                continue
            try:
                value = json.loads(stripped)
            except json.JSONDecodeError as exc:
                if ignore_invalid:
                    continue
                raise ValueError(
                    f"invalid JSON in {path} at line {line_number}: {exc.msg}"
                ) from exc
            if not isinstance(value, dict):
                if ignore_invalid:
                    continue
                raise ValueError(f"expected a JSON object in {path} at line {line_number}")
            yield value


def _contained_path(dataset_dir: Path, path: Path) -> Path:
    """Return an absolute artifact path, refusing paths outside the dataset."""
    candidate = path.resolve()
    if not path.is_absolute() and not candidate.is_relative_to(dataset_dir):
        candidate = (dataset_dir / path).resolve()
    if not candidate.is_relative_to(dataset_dir):
        raise ValueError(f"dataset artifact is outside {dataset_dir}: {path}")
    return candidate


def _read_manifest(dataset_dir: Path, manifest_path: Path) -> _ManifestData:
    upload_files: list[Path] = []
    record_shards: list[Path] = []
    job_id: str | None = None

    for row in _iter_jsonl_objects(manifest_path):
        kind = row.get("kind")
        if kind == "dataset" and job_id is None:
            value = row.get("job_id")
            job_id = str(value) if value else None
        if kind not in _PAYLOAD_KINDS:
            continue

        value = row.get("path")
        if not isinstance(value, str) or not value.strip():
            raise ValueError(f"manifest {manifest_path} has a {kind!r} row without a valid path")
        local_path = _contained_path(dataset_dir, dataset_dir / value)
        upload_files.append(local_path)
        if kind == "shard":
            record_shards.append(local_path)

    return _ManifestData(
        upload_files=tuple(upload_files),
        record_shards=tuple(record_shards),
        job_id=job_id,
    )


def _resolve_dataset(result_or_dir: DeliveryResult | str | Path) -> _DatasetBundle:
    """Normalize a delivery result or directory into one validated bundle."""
    if isinstance(result_or_dir, DeliveryResult):
        dataset_dir = Path(result_or_dir.output_dir).resolve()
    else:
        dataset_dir = Path(result_or_dir).resolve()

    if not dataset_dir.is_dir():
        raise NotADirectoryError(f"dataset directory does not exist: {dataset_dir}")

    raw_manifest = (
        result_or_dir.manifest_path
        if isinstance(result_or_dir, DeliveryResult) and result_or_dir.manifest_path
        else _manifest_if_present(dataset_dir)
    )
    manifest_path = (
        _contained_path(dataset_dir, Path(raw_manifest)) if raw_manifest is not None else None
    )
    manifest = (
        _read_manifest(dataset_dir, manifest_path) if manifest_path is not None else _ManifestData()
    )

    if isinstance(result_or_dir, DeliveryResult):
        upload_files = tuple(
            _contained_path(dataset_dir, Path(path)) for path in result_or_dir.files
        )
    else:
        upload_files = manifest.upload_files

    if manifest_path is None:
        fallback_shards = tuple(
            sorted(
                path
                for path in dataset_dir.iterdir()
                if path.is_file() and path.suffix.lower() in _SHARD_SUFFIXES
            )
        )
        if not upload_files:
            upload_files = fallback_shards
        record_shards = fallback_shards
    else:
        record_shards = manifest.record_shards

    return _DatasetBundle(
        directory=dataset_dir,
        upload_files=upload_files,
        record_shards=record_shards,
        manifest_path=manifest_path,
        job_id=manifest.job_id,
    )


def _manifest_if_present(out: Path) -> Path | None:
    candidate = out / _MANIFEST_NAME
    return candidate if candidate.exists() else None


def _plan_uploads(bundle: _DatasetBundle) -> list[PublishFile]:
    """Plan payloads first, then the manifest and documentation."""
    planned: list[PublishFile] = []
    seen: set[str] = set()

    def repo_path(local: Path) -> str:
        return local.relative_to(bundle.directory).as_posix()

    ordered = sorted(bundle.upload_files, key=repo_path)
    if bundle.manifest_path is not None:
        ordered.append(bundle.manifest_path)
    ordered.extend(bundle.directory / doc for doc in _DOC_FILES)
    for local in ordered:
        remote = repo_path(local)
        if remote == _CARD_NAME or remote in seen or not local.is_file():
            continue
        seen.add(remote)
        planned.append(PublishFile(local_path=local, repo_path=remote))
    return planned


# --- dataset card -------------------------------------------------------------


def stamp_dataset_card(
    dataset_dir: str | Path,
    *,
    license: str,
    task_categories: Sequence[str] | None = None,
    languages: Sequence[str] | None = None,
) -> str:
    """Build the full README.md text with license/task/language frontmatter stamped.

    Reuses an existing card's body (and any other frontmatter keys it carried),
    overrides ``license`` (lowercased, HF convention) / ``task_categories`` /
    ``language``, and appends (or refreshes) a ``## Source provenance`` section
    derived from the shard rows themselves.
    """
    bundle = _resolve_dataset(dataset_dir)
    return _build_dataset_card(
        bundle,
        license=license,
        task_categories=task_categories,
        languages=languages,
    )


def _build_dataset_card(
    bundle: _DatasetBundle,
    *,
    license: str,
    task_categories: Sequence[str] | None,
    languages: Sequence[str] | None,
) -> str:
    """Render a dataset card from an already-resolved bundle."""
    normalized_license = license.strip().lower()
    if not normalized_license:
        raise ValueError("license must not be empty")

    meta: dict[str, Any] = {}
    body = _default_card_body(bundle.job_id or "Dataset")

    existing = bundle.directory / _CARD_NAME
    if existing.exists():
        card_text = existing.read_text(encoding="utf-8")
        parsed_meta, parsed_body = _parse_frontmatter(card_text)
        meta.update(parsed_meta)
        if parsed_body.strip():
            body = parsed_body.rstrip() + "\n"

    meta["license"] = normalized_license
    _set_optional_list(meta, "task_categories", task_categories)
    _set_optional_list(meta, "language", languages)

    body = _replace_section(
        body,
        _PROVENANCE_HEADING,
        _provenance_section(bundle.record_shards),
    )
    front = yaml.safe_dump(meta, sort_keys=False, allow_unicode=True)
    return f"---\n{front.strip()}\n---\n\n{body.rstrip()}\n"


def _set_optional_list(metadata: dict[str, Any], key: str, values: Sequence[str] | None) -> None:
    """Preserve omitted metadata, while allowing an explicit empty list to clear it."""
    if values is None:
        return
    normalized = [str(value) for value in values]
    if normalized:
        metadata[key] = normalized
    else:
        metadata.pop(key, None)


def _default_card_body(title: str) -> str:
    return (
        f"# {title}\n\n"
        "Dataset published from the Agentic Dataset Harness. See `datasheet.md` and "
        "`croissant.json` for documentation and provenance.\n"
    )


def _parse_frontmatter(text: str) -> tuple[dict[str, Any], str]:
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}, text
    try:
        end = next(index for index, line in enumerate(lines[1:], start=1) if line.strip() == "---")
    except StopIteration:
        return {}, text
    loaded = yaml.safe_load("\n".join(lines[1:end]))
    meta = dict(loaded) if isinstance(loaded, dict) else {}
    return meta, "\n".join(lines[end + 1 :])


def _replace_section(body: str, heading: str, replacement: str) -> str:
    """Swap out one ``## <heading>`` section (everything up to the next heading)."""
    lines = body.splitlines()
    start = next((i for i, ln in enumerate(lines) if ln.strip() == f"## {heading}"), None)
    if start is None:
        return body.rstrip() + "\n\n" + replacement.rstrip() + "\n"
    end = next(
        (i for i in range(start + 1, len(lines)) if lines[i].startswith("## ")),
        len(lines),
    )
    return "\n".join([*lines[:start], *replacement.splitlines(), *lines[end:]]).rstrip() + "\n"


@dataclass
class _ProvenanceSummary:
    records: int = 0
    hosts: set[str] = field(default_factory=set)
    licenses: set[str] = field(default_factory=set)


def _provenance_section(shards: Sequence[Path]) -> str:
    """Markdown summarizing where records came from, tallied from JSONL shard rows.

    Parquet shards are skipped (scanning them needs pyarrow); the summary is honest
    about what it scanned.
    """
    channels: dict[str, _ProvenanceSummary] = {}
    scanned = 0
    for shard in shards:
        if shard.suffix.lower() != ".jsonl" or not shard.is_file():
            continue
        scanned += 1
        for row in _iter_jsonl_objects(shard, ignore_invalid=True):
            channel = str(row.get("source_channel") or "unknown")
            summary = channels.setdefault(channel, _ProvenanceSummary())
            summary.records += 1
            host = urlparse(str(row.get("source_url") or "")).netloc
            if host:
                summary.hosts.add(host)
            lic = (str(row.get("source_license") or "").strip().lower()) or "unknown"
            summary.licenses.add(lic)

    lines = [f"## {_PROVENANCE_HEADING}", ""]
    if scanned == 0:
        lines.append("_No JSONL shards found to scan for per-record provenance._")
        return "\n".join(lines)
    if not channels:
        lines.append("_No valid records found in the JSONL shards._")
        return "\n".join(lines)
    for channel in sorted(channels):
        summary = channels[channel]
        hosts = ", ".join(sorted(summary.hosts)) or "n/a (no external URL)"
        licenses = ", ".join(sorted(summary.licenses))
        lines.append(
            f"- **{channel}**: {summary.records} records; sources: {hosts}; "
            f"source licenses: {licenses}"
        )
    return "\n".join(lines)


def _write_if_changed(path: Path, content: str) -> None:
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return
    path.write_text(content, encoding="utf-8")


def _assert_distribution_allowed(
    dataset_dir: Path, *, private: bool, allow_unknown_licensed_assets: bool
) -> None:
    if private or allow_unknown_licensed_assets:
        return

    # Keep the policy check lazy so importing the publishing adapter stays light.
    from .evals import count_unknown_license_assets

    unknown_assets = count_unknown_license_assets(dataset_dir)
    if unknown_assets:
        raise PublishRefusedError(unknown_assets)


def _upload_files(
    hub: HubClient,
    uploads: Sequence[PublishFile],
    *,
    repo_id: str,
    commit_message: str,
) -> tuple[PublishFile, ...]:
    uploaded: list[PublishFile] = []
    for item in uploads:
        url = hub.upload_file(
            path_or_fileobj=str(item.local_path),
            path_in_repo=item.repo_path,
            repo_id=repo_id,
            repo_type=_REPO_TYPE,
            commit_message=commit_message,
        )
        uploaded.append(PublishFile(local_path=item.local_path, repo_path=item.repo_path, url=url))
        logger.info("uploaded %s -> %s", item.repo_path, url)
    return tuple(uploaded)


# --- public entry point -------------------------------------------------------


def publish_dataset(
    result_or_dir: DeliveryResult | str | Path,
    *,
    repo_id: str,
    license: str,
    private: bool = True,
    client: HubClient | None = None,
    dry_run: bool = False,
    allow_unknown_licensed_assets: bool = False,
    task_categories: Sequence[str] | None = None,
    languages: Sequence[str] | None = None,
    commit_message: str = _DEFAULT_COMMIT_MESSAGE,
) -> PublishResult:
    """Upload a written dataset to the HF Hub (or plan the upload with ``dry_run``).

    Uploads shards + manifest + datasheet + croissant, then the stamped dataset
    card. Nothing is uploaded unless this function is explicitly called with
    ``dry_run=False``; ``private=True`` is the default access level. Public
    uploads are refused while the manifest carries unknown-license assets
    (two-layer license policy) unless ``allow_unknown_licensed_assets`` is set.
    Pass an injected ``client`` (anything matching :class:`HubClient`) to stay
    offline — tests do exactly that.
    """
    normalized_repo_id = repo_id.strip()
    if not normalized_repo_id:
        raise ValueError("repo_id must not be empty")

    bundle = _resolve_dataset(result_or_dir)

    uploads = _plan_uploads(bundle)
    card_local = bundle.directory / _CARD_NAME
    card_text = _build_dataset_card(
        bundle,
        license=license,
        task_categories=task_categories,
        languages=languages,
    )
    uploads.append(PublishFile(local_path=card_local, repo_path=_CARD_NAME))

    if dry_run:
        logger.info("dry run: would upload %d files to %s", len(uploads), normalized_repo_id)
        return PublishResult(
            repo_id=normalized_repo_id,
            private=private,
            dry_run=True,
            uploads=tuple(uploads),
        )

    # Distribution gate before local writes and Hub calls: refusal is side-effect free.
    _assert_distribution_allowed(
        bundle.directory,
        private=private,
        allow_unknown_licensed_assets=allow_unknown_licensed_assets,
    )

    hub = client if client is not None else default_hub_client()
    _write_if_changed(card_local, card_text)
    repo_url = hub.create_repo(
        normalized_repo_id,
        repo_type=_REPO_TYPE,
        private=private,
        exist_ok=True,
    )
    uploaded = _upload_files(
        hub,
        uploads,
        repo_id=normalized_repo_id,
        commit_message=commit_message,
    )

    logger.info(
        "published %d files to %s (private=%s)",
        len(uploaded),
        normalized_repo_id,
        private,
    )
    return PublishResult(
        repo_id=normalized_repo_id,
        private=private,
        dry_run=False,
        uploads=uploaded,
        url=str(repo_url),
    )
